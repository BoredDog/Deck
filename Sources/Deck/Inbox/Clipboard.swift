import AppKit
import SwiftUI

/// Remembers the last 50 things you copied, encrypted on disk, and forgets them after a day.
/// Password managers mark their copies as concealed or transient; those are never stored, nor is text that looks like a password.
/// Without the Keychain key, history stays in memory only.
@MainActor final class Clipboard: ObservableObject {
    static let shared = Clipboard()

    struct Item: Codable, Identifiable, Equatable {
        var id = UUID()
        var date = Date.now
        var text: String?
        var image: Data?
    }

    @Published private(set) var items: [Item] = []
    @AppStorage("clipboardHours") var keepHours = 24
    @AppStorage("clipboardIgnore") var ignoreList = "1Password, Bitwarden, Keychain Access, Passwords"
    @AppStorage("clipboardOn") var on = true

    static let maxItems = 50
    nonisolated static let maxImageBytes = 20_000_000
    nonisolated static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?
    private let disk = DispatchQueue(label: "deck.clipboard")   // one at a time, in order: a clear never races a save
    private var file: URL { Vault.folder.appendingPathComponent("clipboard.bin") }

    /// True when this copy must not be remembered.
    nonisolated static func shouldSkip(types: [String], frontApp: String?, ignore: [String]) -> Bool {
        if types.contains(where: skipTypes.contains) { return true }
        guard let app = frontApp else { return false }
        return ignore.contains { $0.caseInsensitiveCompare(app) == .orderedSame }
    }

    /// A single 8–64 character word mixing at least 3 of: lowercase, uppercase, digits, symbols. Links and paths are kept.
    nonisolated static func looksLikeSecret(_ s: String) -> Bool {
        guard (8...64).contains(s.count), !s.contains(where: { $0.isWhitespace }),
              !s.contains("://"), !s.lowercased().hasPrefix("www."), !s.hasPrefix("/"), !s.hasPrefix("~") else { return false }
        let kinds = [s.contains { $0.isLowercase }, s.contains { $0.isUppercase }, s.contains { $0.isNumber },
                     s.contains { !$0.isLetter && !$0.isNumber }]
        return kinds.filter { $0 }.count >= 3
    }

    /// Keeps the newest images up to `maxBytes` in total; older images are dropped first.
    nonisolated static func cappingImages(_ items: [Item], maxBytes: Int = maxImageBytes) -> [Item] {
        var total = 0
        return items.filter { item in
            guard let n = item.image?.count else { return true }
            total += n
            return total <= maxBytes
        }
    }

    /// Follows the "Remember what I copy" switch: off stops watching and forgets everything.
    func applySetting() { if on { start() } else { stop() } }

    func stop() {
        timer?.invalidate()
        timer = nil
        clear()
    }

    func start() {
        guard on, timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        if let data = try? Data(contentsOf: file), let plain = try? Vault.open(data) {
            items = (try? JSONDecoder().decode([Item].self, from: plain)) ?? []
        }
        expire()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { Clipboard.shared.tick() }
        }
    }

    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = item.text { pb.setString(t, forType: .string) }
        else if let d = item.image { pb.setData(d, forType: .tiff) }
        lastChange = pb.changeCount
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        saveTask?.cancel()
        let file = file
        disk.async { try? FileManager.default.removeItem(at: file) }
    }

    private func tick() {
        expire()
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let ignore = ignoreList.split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
        let types = (pb.types ?? []).map(\.rawValue)
        guard !Clipboard.shouldSkip(types: types, frontApp: NSWorkspace.shared.frontmostApplication?.localizedName, ignore: ignore) else { return }

        var item = Item()
        if let s = pb.string(forType: .string), !s.isEmpty {
            guard !Clipboard.looksLikeSecret(s.trimmingCharacters(in: .whitespacesAndNewlines)) else { return }
            item.text = s
            items.removeAll { $0.text == s }
        } else if let img = pb.data(forType: .png) ?? pb.data(forType: .tiff), img.count < 10_000_000 {
            item.image = img
        } else { return }
        items.insert(item, at: 0)
        if items.count > Clipboard.maxItems { items.removeLast(items.count - Clipboard.maxItems) }
        items = Clipboard.cappingImages(items)
        save()
    }

    private func expire() {
        let cutoff = Date.now.addingTimeInterval(-Double(keepHours) * 3600)
        if items.contains(where: { $0.date < cutoff }) {
            items.removeAll { $0.date < cutoff }
            save()
        }
    }

    /// Waits for 1 second of quiet, then encrypts and writes off the main thread. No key: nothing is written.
    private func save() {
        saveTask?.cancel()
        saveTask = Task { @MainActor in
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            let snapshot = items, file = file
            disk.async {
                guard let plain = try? JSONEncoder().encode(snapshot), let sealed = try? Vault.seal(plain) else { return }
                try? sealed.write(to: file, options: .atomic)
            }
        }
    }
}
